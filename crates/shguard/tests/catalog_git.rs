#[test]
fn git_cannot_be_chained_into_an_allow() {
    assert_not_allow(&[
        "git log; git reset --hard",
        "git status && git clean -fdx",
        "git log | git apply",
        "git log --output=/tmp/x && git status",
    ]);
}

